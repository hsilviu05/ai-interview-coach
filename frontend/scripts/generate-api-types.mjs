import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const scriptDirectory = path.dirname(new URL(import.meta.url).pathname);
const frontendRoot = path.resolve(scriptDirectory, '..');
const repoRoot = path.resolve(frontendRoot, '..');
const schemaPath = path.join(repoRoot, 'backend', 'openapi-v1.json');
const outputDirectory = path.join(
  frontendRoot,
  'src',
  'app',
  'core',
  'api',
  'generated'
);
const outputPath = path.join(outputDirectory, 'backend-api.ts');

const document = JSON.parse(readFileSync(schemaPath, 'utf8'));
const generated = generateTypes(document);
mkdirSync(outputDirectory, { recursive: true });
writeFileSync(outputPath, generated, 'utf8');
console.log(`Generated ${path.relative(repoRoot, outputPath)}`);

function generateTypes(document) {
  const schemas = document?.components?.schemas ?? {};
  const names = Object.keys(schemas).sort((left, right) => left.localeCompare(right));

  const declarations = names.map(name => emitSchemaDeclaration(name, schemas[name]));

  return [
    '// Auto-generated by `npm run generate:api-types`.',
    '// Do not edit this file by hand.',
    '',
    declarations.join('\n\n'),
    '',
  ].join('\n');
}

function emitSchemaDeclaration(name, schema) {
  if (shouldEmitInterface(schema)) {
    return `export interface ${name} ${emitObjectBody(schema)}`;
  }

  return `export type ${name} = ${resolveSchemaType(schema)};`;
}

function shouldEmitInterface(schema) {
  return Boolean(
    schema &&
      !schema.$ref &&
      !schema.enum &&
      !schema.allOf &&
      !schema.oneOf &&
      !schema.anyOf &&
      (schema.type === 'object' || schema.properties)
  );
}

function emitObjectBody(schema) {
  const required = new Set(schema.required ?? []);
  const properties = schema.properties ?? {};
  const entries = Object.entries(properties);

  if (entries.length === 0 && schema.additionalProperties) {
    return `{ [key: string]: ${resolveSchemaType(schema.additionalProperties)}; }`;
  }

  const lines = entries.map(([propertyName, propertySchema]) => {
    const optional = required.has(propertyName) ? '' : '?';
    return `  ${quotePropertyIfNeeded(propertyName)}${optional}: ${resolveSchemaType(propertySchema)};`;
  });

  if (schema.additionalProperties) {
    lines.push(
      `  [key: string]: ${resolveSchemaType(schema.additionalProperties)};`
    );
  }

  if (lines.length === 0) {
    return '{}';
  }

  return `{\n${lines.join('\n')}\n}`;
}

function resolveSchemaType(schema) {
  if (!schema) {
    return 'unknown';
  }

  if (schema.$ref) {
    return applyNullable(resolveReference(schema.$ref), schema);
  }

  if (schema.enum) {
    const union = schema.enum.map(value => JSON.stringify(value)).join(' | ');
    return applyNullable(union || 'string', schema);
  }

  if (schema.allOf) {
    return applyNullable(
      schema.allOf.map(item => resolveSchemaType(item)).join(' & '),
      schema
    );
  }

  if (schema.oneOf) {
    return applyNullable(
      schema.oneOf.map(item => resolveSchemaType(item)).join(' | '),
      schema
    );
  }

  if (schema.anyOf) {
    return applyNullable(
      schema.anyOf.map(item => resolveSchemaType(item)).join(' | '),
      schema
    );
  }

  if (schema.type === 'array') {
    return applyNullable(`(${resolveSchemaType(schema.items)})[]`, schema);
  }

  if (schema.type === 'object' || schema.properties) {
    return applyNullable(emitInlineObject(schema), schema);
  }

  if (schema.type === 'integer' || schema.type === 'number') {
    return applyNullable('number', schema);
  }

  if (schema.type === 'boolean') {
    return applyNullable('boolean', schema);
  }

  if (schema.type === 'string') {
    return applyNullable('string', schema);
  }

  return 'unknown';
}

function emitInlineObject(schema) {
  if (schema.additionalProperties && !schema.properties) {
    return `Record<string, ${resolveSchemaType(schema.additionalProperties)}>`;
  }

  return emitObjectBody(schema);
}

function resolveReference(reference) {
  return reference.split('/').at(-1) ?? 'unknown';
}

function applyNullable(type, schema) {
  if (schema.nullable) {
    return `${type} | null`;
  }

  return type;
}

function quotePropertyIfNeeded(propertyName) {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(propertyName)
    ? propertyName
    : JSON.stringify(propertyName);
}
